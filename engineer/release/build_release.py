def build(dist, emit_source_docs=False):
    eng_dst = os.path.join(dist, "engineer")
    data_dst = os.path.join(eng_dst, "data")
    rel_dst = os.path.join(eng_dst, "release")
    for d in (eng_dst, data_dst, rel_dst):
        os.makedirs(d, exist_ok=True)

    manifest = []      # (rel_path_in_dist, source_path, sha256, note)
    notes = []         # human-facing build notes

    # 1) engineer source/docs, with scrub + patch where relevant
    for name in ENGINEER_FILES:
        src = os.path.join(ENGINEER, name)
        if not os.path.exists(src):
            raise RuntimeError(f"required source missing: {src}")
        with open(src, "r", encoding="utf-8") as f:
            text = f.read()
        scrub_n = 0
        if name in ("ext_gym.py", "ext_ldo.py"):
            text, scrub_n = scrub_source(text)
            if scrub_n:
                notes.append(f"scrubbed {scrub_n} hardcoded scratch path(s) in {name}")
        elif name == "tasks.py":
            text = patch_tasks(text)
            notes.append("patched tasks.py: --list works without lna/ via "
                         "tasks_registry_v0.json; --check guarded")
        doc_n = 0
        if name.endswith(".md"):
            text, doc_n = scrub_doc(text)
            if doc_n:
                notes.append(f"normalised {doc_n} machine path(s) in {name}")
        dst = os.path.join(eng_dst, name)
        with open(dst, "w", encoding="utf-8") as f:
            f.write(text)
        rel = os.path.relpath(dst, dist)
        note = ("scrubbed" if (scrub_n or doc_n) else
                ("patched" if name == "tasks.py" else ""))
        manifest.append((rel, os.path.relpath(src, ROOT), sha256_file(dst), note))

    # 2) aggregated scoreboards + goldens
    for key, fname, required in DATA_FILES:
        src = os.path.join(ENGINEER, "data", fname)
        if not os.path.exists(src):
            if required:
                raise RuntimeError(f"required data artifact missing: {src}")
            notes.append(f"data artifact absent, skipped (tolerated): {fname}")
            continue
        with open(src, "r", encoding="utf-8") as f:
            jtext = f.read()
        jtext, jn = scrub_json(jtext)
        dst = os.path.join(data_dst, fname)
        with open(dst, "w", encoding="utf-8") as f:
            f.write(jtext)
        if jn:
            notes.append(f"normalised {jn} provenance path(s) in {fname}")
        manifest.append((os.path.relpath(dst, dist),
                         os.path.relpath(src, ROOT), sha256_file(dst),
                         "scrubbed" if jn else ""))

    # 3) generate the shipped registry JSON (needs lna on THIS box)
    sys.path.insert(0, HERE)
    import export_registry                                     # noqa: E402
    reg_dst = os.path.join(eng_dst, "tasks_registry_v0.json")
    export_registry.export(reg_dst)
    manifest.append((os.path.relpath(reg_dst, dist),
                     "generated by release/export_registry.py",
                     sha256_file(reg_dst), "generated"))
    notes.append("generated tasks_registry_v0.json from live REGISTRY")

    # 4) release/ tools
    for name in RELEASE_FILES:
        src = os.path.join(HERE, name)
        dst = os.path.join(rel_dst, name)
        shutil.copy2(src, dst)
        manifest.append((os.path.relpath(dst, dist),
                         os.path.relpath(src, ROOT), sha256_file(dst), ""))

    # 5) README_RELEASE.md, LICENSE placeholder
    readme_dst = os.path.join(eng_dst, "README_RELEASE.md")
    with open(readme_dst, "w", encoding="utf-8") as f:
        f.write(render_readme())
    manifest.append((os.path.relpath(readme_dst, dist), "release/build_release.py",
                     sha256_file(readme_dst), "assembled"))

    license_dst = os.path.join(dist, "LICENSE")
    with open(license_dst, "w", encoding="utf-8") as f:
        f.write(render_license())
    manifest.append((os.path.relpath(license_dst, dist), "release/build_release.py",
                     sha256_file(license_dst), "placeholder"))

    # 6) MANIFEST.md (also copied into release/ so it lives with the source)
    manifest_text = render_manifest(manifest, notes)
    for path in (os.path.join(dist, "MANIFEST.md"),):
        with open(path, "w", encoding="utf-8") as f:
            f.write(manifest_text)
    # add MANIFEST.md itself last (self-listing without its own hash, noted)
    m_dst = os.path.join(dist, "MANIFEST.md")
    manifest.append((os.path.relpath(m_dst, dist), "release/build_release.py",
                     "(self; regenerate to verify)", "assembled"))

    # 7) verify grep-clean
    findings = verify_clean(dist)

    # 8) optionally drop the canonical committed copies into the SOURCE release/
    # dir (engineer/release/) so README_RELEASE.md / LICENSE / MANIFEST.md are
    # reviewable in the repo and never hand-edited -- they are regenerated here.
    if emit_source_docs:
        shutil.copy2(readme_dst, os.path.join(HERE, "README_RELEASE.md"))
        shutil.copy2(license_dst, os.path.join(HERE, "LICENSE"))
        shutil.copy2(m_dst, os.path.join(HERE, "MANIFEST.md"))
        notes.append("emitted canonical README_RELEASE.md / LICENSE / "
                     "MANIFEST.md into engineer/release/ (source copies)")

    return dist, manifest, notes, findings


def verify_clean(dist):
    findings = {p: [] for p in FORBIDDEN}
    # The build script itself legitimately NAMES the forbidden patterns (its
    # FORBIDDEN list, scrub regexes, and doc strings). Scanning it would be a
    # guaranteed false positive, so it is excluded -- the scrub target is the
    # payload (env/benchmark/data/docs), not the assembler that names the rules.
    skip = {"build_release.py"}
    for root, _dirs, files in os.walk(dist):
        for fn in files:
            if fn in skip:
                continue
            path = os.path.join(root, fn)
            try:
                with open(path, "r", encoding="utf-8", errors="ignore") as f:
                    text = f.read()
            except Exception:                                  # noqa: BLE001
                continue
            for pat in FORBIDDEN:
                if re.search(pat, text):
                    findings[pat].append(os.path.relpath(path, dist))
    return findings


