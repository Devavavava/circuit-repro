def render_manifest(manifest, notes):
    lines = []
    lines.append("# MANIFEST -- engineer env+benchmark release\n")
    lines.append("Assembled by `engineer/release/build_release.py` from the live "
                 f"circuit-repro `engineer` branch at git `{git_sha(ENGINEER)}`.\n")
    lines.append("Scope: environment + benchmark ONLY (case study staged later). "
                 "License placeholder (TBD at publish). 45 nm model card NOT "
                 "bundled (manual fetch, license unknown). VACASK out (AGPL). "
                 "Data = aggregated scoreboards + goldens only.\n")
    lines.append("## Files in the assembled tree\n")
    lines.append("| path in package | source (relative to repo root) | sha256 | note |")
    lines.append("|---|---|---|---|")
    for rel, src, sha, note in sorted(manifest):
        lines.append(f"| `{rel}` | `{src}` | `{sha}` | {note} |")
    lines.append(f"\n**{len(manifest)} files** in the assembled tree.\n")
    lines.append("## Build notes\n")
    for n in notes:
        lines.append(f"- {n}")
    lines.append("\n## Exclusions -- what is NOT in this package, and why\n")
    for item, why in EXCLUSIONS:
        lines.append(f"- **{item}** -- {why}")
    lines.append("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    default_dist = os.path.join(os.environ.get("SCRATCH",
                    os.environ.get("TMPDIR", "/tmp")), "engineer_release", "dist")
    ap.add_argument("--dist", default=default_dist,
                    help="output dist/ dir (default: $SCRATCH/engineer_release/dist)")
    ap.add_argument("--clean", action="store_true",
                    help="remove the dist dir first")
    ap.add_argument("--emit-source-docs", action="store_true",
                    help="also write the canonical README_RELEASE.md / LICENSE "
                         "/ MANIFEST.md into engineer/release/ (the committed copies)")
    a = ap.parse_args()
    if a.clean and os.path.isdir(a.dist):
        shutil.rmtree(a.dist)
    dist, manifest, notes, findings = build(a.dist,
                                            emit_source_docs=a.emit_source_docs)

    print(f"assembled -> {dist}")
    print(f"  {len(manifest)} files")
    for n in notes:
        print(f"  note: {n}")
    print("scrub verification (forbidden-pattern grep counts, want 0):")
    ok = True
    for pat, hits in findings.items():
        print(f"  {pat!r}: {len(hits)}" + (f"  {hits}" if hits else ""))
        if hits:
            ok = False
    print("scrub: " + ("CLEAN" if ok else "DIRTY -- FIX BEFORE RELEASE"))
    return 0 if ok else 1


