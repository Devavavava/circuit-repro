def sha256_file(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def git_sha(cwd):
    try:
        r = subprocess.run(["git", "rev-parse", "HEAD"], cwd=cwd,
                           capture_output=True, text=True, timeout=10)
        return (r.stdout or "").strip() or "UNKNOWN"
    except Exception:                                          # noqa: BLE001
        return "UNKNOWN"


# ---- scrubbing (applied to the assembled copy only) -----------------------
_SCRATCH_LIVE = re.compile(
    r'"/home/dpatni/\.claude/jobs/[^"]*?/tmp/(ext(?:_ldo)?_scratch)"')


def scrub_source(text):
    """Rewrite any hardcoded /home/dpatni scratch fallback to a tempfile
    default. Idempotent: if the live fix already landed this is a no-op."""
    n = [0]

    def repl(m):
        n[0] += 1
        name = m.group(1)
        # Replace ONLY the string literal with a bare expression -- no inline
        # comment, because the literal sits mid-call (`os.environ.get(KEY, <here>)`)
        # and a `#` would comment out the closing paren. The scrub is recorded in
        # the build notes / MANIFEST instead.
        return f'os.path.join(tempfile.gettempdir(), "{name}")'

    out = _SCRATCH_LIVE.sub(repl, text)
    if n[0] and "import tempfile" not in out:
        out = out.replace("import os\n", "import os\nimport tempfile\n", 1)
    return out, n[0]


def scrub_doc(text):
    """Normalise machine-specific absolute paths and identity tokens in assembled
    docs. Replaces the /home/dpatni/circuit-repro[-engineer] prefixes, the Claude
    scratch paths, the build-box username, and the author's Windows home path with
    neutral tokens so a public doc does not leak the build box's identity/layout.
    Counts hits. (E5-PACKAGING.md §4.3 names `devavrat` and `C:\\Users\\Devavrat`
    literally, in prose that reports the scrub search itself -- those literals are
    normalised here too so the assembled doc greps clean.)"""
    n = 0
    for pat, sub in [
        (r"/home/dpatni/circuit-repro-engineer", "<repo>"),
        (r"/home/dpatni/circuit-repro", "<repo>"),
        (r"/home/dpatni/\.claude/jobs/[^\s`\"']*", "<scratch>"),
        (r"/home/dpatni", "<home>"),
        (r"C:\\Users\\Devavrat[^\s`\"']*", "<win-home>"),
        (r"C:\\Users", "<win-home>"),
        (r"(?i)devavrat", "<user>"),
    ]:
        text, k = re.subn(pat, sub, text)
        n += k
    return text, n


def scrub_json(text):
    """Normalise machine-specific provenance paths in shipped data artifacts.
    Scoreboards/goldens carry a `harness` block that stamps the absolute ngspice
    (and, in per-cell JSONs, model-card/zoaf) paths resolved on the build box --
    a provenance stamp by design, but it leaks the /home/dpatni prefix. For the
    aggregated artifacts that DO ship, normalise the prefix to <repo> while
    leaving the rest of the stamp (binary name, version) intact. Counts hits."""
    n = 0
    for pat, sub in [
        (r"/home/dpatni/circuit-repro-engineer", "<repo>"),
        (r"/home/dpatni/circuit-repro", "<repo>"),
        (r"/home/dpatni/\.claude/jobs/[^\s`\"']*", "<scratch>"),
        (r"/home/dpatni", "<home>"),
    ]:
        text, k = re.subn(pat, sub, text)
        n += k
    return text, n


