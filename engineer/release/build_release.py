def patch_tasks(text):
    """Insert the JSON-backed --list fallback and the --check guard."""
    if _TASKS_ORIG_IMPORTS not in text:
        raise RuntimeError("tasks.py import block not found verbatim; the "
                           "release patch is out of date with the live file")
    text = text.replace(_TASKS_ORIG_IMPORTS, _TASKS_PATCHED_IMPORTS, 1)
    # Guard cmd_check(): prepend the loud-fail body.
    text = text.replace("def cmd_check():\n", _TASKS_CHECK_GUARD, 1)
    # Prepend the offline provenance line to cmd_list().
    if "def cmd_list(long=False):\n" not in text:
        raise RuntimeError("tasks.py cmd_list signature changed; patch is stale")
    text = text.replace("def cmd_list(long=False):\n", _TASKS_LIST_PROV, 1)
    return text


