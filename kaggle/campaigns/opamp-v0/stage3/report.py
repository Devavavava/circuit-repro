"""Stage 3 report: per-task D0 analysis -> d0-summary.json + d0-tables.md (stage3/).
Also cross-checks the D0 runs that coincide with Stage-2 preview runs (same circuit, spec,
seed, evals, objective) for bit-identical targets (determinism; the preview changes no rule).
Usage: run_cr.sh kaggle/campaigns/opamp-v0/stage3/report.py
"""
import json
import math
import os

import d0common as C
import d0

INF = math.inf
CEIL = json.load(open(os.path.join(C.RESULTS, "ceiling.json")))
A_DB = CEIL["a_max_db"]
UNIT = {"R1": "dB", "R23": "MHz·pF/mA", "R4": "V"}
GAIN_MIN = {"R1": None, "R23": 80.0, "R4": 40.0}


def k_of(did):
    p = did.split(":")
    if p[0] in ("F1", "W"):
        return CEIL["k_topology"][p[1]]
    base = CEIL["k_topology"][p[1]]
    if p[0] == "F2":
        d = [x for x in C.f2_designs(p[1]) if x["i"] == int(p[2])][0]
        return base + (1 if d["kind"] == "addMOS" else 0)
    d = [x for x in C.te_designs(p[1]) if x["j"] == int(p[2])][0]
    return base + sum(1 for e in d["edits"] if e[0] == "addMOS")


def ceil_db(did):
    return k_of(did) * A_DB


def edit_of(did):
    p = did.split(":")
    if p[0] == "F2":
        return " ".join(map(str, [x for x in C.f2_designs(p[1]) if x["i"] == int(p[2])][0]["edit"]))
    if p[0] == "TE":
        d = [x for x in C.te_designs(p[1]) if x["j"] == int(p[2])][0]
        return " + ".join(" ".join(map(str, e)) for e in d["edits"])
    return ""


def fv(x, reg=None):
    if x is None:
        return "inf."
    if x == -INF:
        return "−∞"
    if x == INF:
        return "+∞"
    if reg == "R23":
        return "%.0f" % x
    if reg == "R4":
        return "%.3f" % x
    return "%.2f" % x


def stage2_crosscheck(res):
    rows = []
    s2 = C.S2.RESULTS
    for r in res.values():
        if r["phase"] != "frontier" or r.get("calib") != 0:
            continue
        name = r["design"].split(":")[1]
        tag = "max-%s-%s%s.json" % (r["regime"], name, "" if r["seed"] == 1 else "-s%d" % r["seed"])
        p = os.path.join(s2, tag)
        if not os.path.exists(p):
            continue
        s = json.load(open(p))["summary"]
        same = (bool(s["feasible"]) == bool(r["feasible"]) and s["target_raw"] is not None
                and r["target_raw"] is not None
                and abs(float(s["target_raw"]) - float(r["target_raw"])) <= 1e-6 * max(1.0, abs(float(s["target_raw"]))))
        rows.append({"tag": tag[:-5], "d0": r["target_raw"], "stage2": s["target_raw"], "identical": same})
    return sorted(rows, key=lambda x: x["tag"])


def cpu_by_phase(res):
    out = {}
    for r in res.values():
        out[r["phase"]] = out.get(r["phase"], 0.0) + (r.get("cpu_s") or 0.0) / 3600.0
    out["total"] = sum(out.values())
    return out


def main():
    res = C.load_results()
    tasks = [d0.analyse_task(a, r, res) for a, r in C.TASKS]
    for t in tasks:
        reg = t["regime"]
        t["witness"]["ceiling_db"] = ceil_db(t["witness"]["design"])
        for d in t["refs"]:
            d["ceiling_db"] = ceil_db(d["design"])
            d["edit"] = edit_of(d["design"])
        for d in t["te"]["top"]:
            d["ceiling_db"] = ceil_db(d["design"])
            d["edit"] = edit_of(d["design"])
        best = t["refs"][0]
        t["best_ref_ceiling_db"] = best["ceiling_db"]
        if reg == "R1":
            t["backstop_note"] = (
                "best reference's ceiling %.1f dB >= witness M* %.2f dB: the gap is NOT forced by the "
                "analytic ceiling (witness wins by losing less to the sizer)" % (
                    best["ceiling_db"], t["witness"]["Mstar"])
                if best["ceiling_db"] >= t["witness"]["Mstar"] else
                "best reference's ceiling %.1f dB < witness M*: gap backed by the ceiling" % best["ceiling_db"])
        else:
            gm = GAIN_MIN[reg]
            t["backstop_note"] = "gain ceilings vs the regime's gain floor %.0f dB: witness %.1f, best ref %.1f" % (
                gm, t["witness"]["ceiling_db"], best["ceiling_db"])
    v = d0.verdict(tasks)
    summ = {"verdict": v, "tasks": tasks, "cpu_h": cpu_by_phase(res), "ceiling": CEIL,
            "stage2_crosscheck": stage2_crosscheck(res), "n_records": len(res)}
    with open(os.path.join(C.HERE, "d0-summary.json"), "w") as fh:
        json.dump(summ, fh, indent=1, sort_keys=True, default=lambda x: str(x))
    L = ["# opamp-v0 Stage 3 — D0 tables", "",
         "Generated by `stage3/report.py` from `stage3/results/jobs.jsonl`. M* = median over seeds 1–3 "
         "(infeasible = −∞). Hard constraints = PREREG Stage 3 + the stability gate (Amendment 1). "
         "Ceiling = k·%.2f dB (best gm·ro at L = 1 µm, %s; k = gm·ro factors, D-O27)." % (
             A_DB, "PMOS"), ""]
    L += ["## Verdict", "", "**%s** — accepted %d/6 (%s); accepted and not \"≤ 2 edits\": %d." % (
        v["verdict"], v["n_accepted"], ", ".join(v["accepted"]) or "none", v["n_accepted_not_le2"]), ""]
    L += ["## Per task", "",
          "| task | calib | witness seeds | W M* | best reference | ref seeds | ref M* | G | min gap | gap | "
          "confirmation | two-edit | W ceiling dB | ref ceiling dB | accepted |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for t in tasks:
        reg = t["regime"]
        b = t["refs"][0]
        if t.get("confirm_w_ok") is not None:
            nref = sum(1 for ok in t["confirm_refs_ok"].values() if ok)
            conf = "W %d/3 feasible; refs meeting the rule %d/5" % (
                sum(1 for x in t["confirm"]["W:" + C.WITNESS[reg]] if x["feasible"]), nref)
        else:
            conf = "not run (gap below minimum)" if not t["gap_pass"] else "pending"
        gtxt = fv(t["G"], reg) + (" (%+.1f %%)" % (100 * t["G_rel"]) if t.get("G_rel") is not None else "")
        L.append("| %s / %s | %d | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %.1f | %.1f | %s |" % (
            t["anchor"], reg, t["calib_step"], " / ".join(fv(x, reg) for x in t["witness"]["seeds"]),
            fv(t["witness"]["Mstar"], reg), b["design"], " / ".join(fv(x, reg) for x in b["seeds"]),
            fv(b["Mstar"], reg), gtxt, fv(t["G_min"], reg), "pass" if t["gap_pass"] else "FAIL", conf,
            t.get("two_edit_label", "n/a (no threshold)"), t["witness"]["ceiling_db"], b["ceiling_db"],
            "**yes**" if t["accepted"] else "no"))
    L += ["", "Backstop notes:", ""]
    for t in tasks:
        L.append("- %s / %s: %s" % (t["anchor"], t["regime"], t["backstop_note"]))
    for t in tasks:
        reg = t["regime"]
        L += ["", "## %s / %s — references (F1 + top-%d F2′), M in %s" % (t["anchor"], reg, C.TOP_F2, UNIT[reg]), "",
              "F2′ screen (300 evals, seed 1): %d designs, %d feasible, best %s. Witness %s: %s → M* %s." % (
                  t["f2_screen"]["n"], t["f2_screen"]["n_feasible"], fv(t["f2_screen"]["best"], reg),
                  t["witness"]["design"], " / ".join(fv(x, reg) for x in t["witness"]["seeds"]),
                  fv(t["witness"]["Mstar"], reg)), "",
              "| rank | design | edit | screen | seed 1 | seed 2 | seed 3 | M* | ceiling dB |",
              "|---|---|---|---|---|---|---|---|---|"]
        for i, d in enumerate(t["refs"]):
            L.append("| %d | %s | %s | %s | %s | %s | %s | %s | %.1f |" % (
                i + 1, d["design"], d["edit"], fv(d.get("screen"), reg) if "screen" in d else "",
                *(fv(x, reg) for x in d["seeds"]), fv(d["Mstar"], reg), d["ceiling_db"]))
        if t.get("confirm"):
            L += ["", "Confirmation spec: hard + %s ≥ %s (= ref M* + G/2); margin objective; reference rule: "
                  "infeasible 3/3 with worst normalized margin ≤ %.4f (= −(G/4)/max(|limit|,1))." % (
                      t["M"], fv(t["thr"], reg), t["confirm_margin_limit"]), "",
                  "| design | seed | feasible | worst margin | M | meets rule |", "|---|---|---|---|---|---|"]
            for did, rows in t["confirm"].items():
                ok = ("W ≥ 2/3: %s" % t.get("confirm_w_ok")) if did.startswith("W:") else str(
                    t.get("confirm_refs_ok", {}).get(did))
                for x in rows:
                    if x is None:
                        continue
                    L.append("| %s | %d | %s | %s | %s | %s |" % (
                        did, x["seed"], x["feasible"],
                        "%.4f" % x["worst_margin"] if x["worst_margin"] is not None else "—",
                        fv(x["M"], reg), ok))
        te = t["te"]
        L += ["", "Two-edit check: %d designs screened, %d feasible; top-%d at 2,500 evals seed 1%s." % (
            te["n"], te["n_feasible"], C.TOP_TE,
            (" — threshold %s; screen hits %d; 2,500-eval hits %s → **%s**" % (
                fv(t["thr"], reg), te["hits_screen"], ", ".join(te["hits_full"]) or "none",
                t["two_edit_label"])) if t["thr"] is not None else " (no threshold: gap below minimum)"), "",
              "| design | edits | screen | 2,500 s1 | ceiling dB |", "|---|---|---|---|---|"]
        for d in te["top"]:
            L.append("| %s | %s | %s | %s | %.1f |" % (d["design"], d["edit"], fv(d["screen"], reg),
                                                     fv(d["full"], reg), d["ceiling_db"]))
    L += ["", "## CPU (h)", "", "| phase | CPU-h |", "|---|---|"]
    for k, x in sorted(summ["cpu_h"].items()):
        L.append("| %s | %.2f |" % (k, x))
    xc = summ["stage2_crosscheck"]
    L += ["", "## Determinism cross-check vs Stage-2 preview runs (same job)", "",
          "%d coinciding runs, %d bit-identical targets." % (len(xc), sum(1 for x in xc if x["identical"])), ""]
    for x in xc:
        L.append("- %s: D0 %s, Stage 2 %s, identical %s" % (x["tag"], x["d0"], x["stage2"], x["identical"]))
    with open(os.path.join(C.HERE, "d0-tables.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L[:40]))
    print(json.dumps(v))


if __name__ == "__main__":
    main()
