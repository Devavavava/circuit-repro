"""_gen_ladder.py -- emit the capability-v0 experimental spec ladder.

Run once to (re)generate the 24 `cap-<tier><nn>-<hint>.yaml` files and
`ladder.json` in this directory. The generated YAMLs are the committed
artefacts; this script is kept alongside them only to document exactly how the
numbers were derived (provenance, house rule -- no magic constants).

EXPERIMENTAL / capability-v0. NONE of these specs is frozen protocol. Adoption
or freezing of any target is a USER RULING (memory: circuit-repro-governance).

Calibration policy (brief + G0-FAIRNESS "calibrations.allowed:never"): every
number is a round, published-practice figure or a relaxed/tightened step off the
three real bring-up specs -- wifi24 (2.4 GHz), ism58 (5.8 GHz), gps-l1
(1.575 GHz) -- NOT read off this pipeline's behaviour. device_budget / l_min /
l_max / sizing ranges are COPIED verbatim from those specs per band.

Grading axes (loose -> tight), per the brief:
    band     0.9 / 1.575 / 2.4 / 3.5 / 5.8 GHz narrowband + 2 wideband
    NF max   3.5 -> 1.5 dB
    S11 max  -8 -> -15 dB
    S21 min  10 -> 20 dB
    Idd max  15 -> 5 mA

Tiers:
    E (8) loose everything -- the sanity floor (should be broadly clearable)
    M (8) realistic commercial-ish middle
    H (8) tight combinations (low NF + tight match + low power at once),
          incl. one 5.8 GHz-tight and one wideband with band-wide S11.

Exactly TWO wideband entries (brief): cap-e08 (loose) and cap-h08 (tight,
band-wide S11); both reuse the wideband screen (allow_inductorless true,
s11_max_db + s21_ripple_db band-wide). The other 22 are narrowband.

iip3_dbm is declared on EVERY spec with `status: unsupported` -- the schema
value that means MEASURED-BUT-NOT-GATED reporting is *not* what we want here:
`status: measured` would make spec.feasible() gate iip3 (and a missing metric
= violated). The campaign measures IIP3 post-sizing as an ADVISORY column via
verify.py regardless of this status, so `unsupported` keeps it un-gated in the
sizing loop while still declaring the target. (See spec.py D5/D5b + plans2/23.)
"""
