def _num(x):
    """YAML scalar: keep engineering floats in 1e-9 form, ints as ints."""
    if isinstance(x, float):
        # engineering notation, matching the real specs (e.g. 2.442e9, 3e-10),
        # not python's 2442000000.0 repr.
        return ("%g" % x)
    return str(x)


def _yaml_str(s):
    """Quote a scalar that YAML would otherwise mis-parse (colon-space, etc.)."""
    return '"%s"' % s.replace('"', '\\"')


def emit(spec_id, tier, name, desc, band, nb_key, cons, objs, topo, note):
    """Render one spec YAML string."""
    L = []
    L.append(HDR.format(tier=tier.upper(), tier_note=TIER_NOTE[tier]))
    L.append("# %s\n" % note)
    L.append("name: %s" % name)
    L.append("description: %s\n" % _yaml_str(desc))
    L.append("process:")
    L.append("  models: AutoCkt/repo/eval_engines/ngspice/ngspice_inputs/spice_models/45nm_bulk.txt")
    L.append("  vdd: 1.1")
    L.append("  temp: 27\n")
    L.append("band:")
    L.append("  type: %s" % band["type"])
    L.append("  f0: %s" % _num(band["f0"]))
    L.append("  f_lo: %s" % _num(band["f_lo"]))
    L.append("  f_hi: %s" % _num(band["f_hi"]))
    L.append("")
    L.append("ports:")
    L.append("  z0: 50")
    L.append("  input: VIN1")
    L.append("  output: VOUT1\n")
    L.append("constraints:")
    for k, v in cons:
        L.append("  %s" % _fmt_constraint(k, v))
    L.append("")
    L.append("objectives:")
    for o in objs:
        L.append("  - {metric: %s, direction: %s, weight: %s}"
                 % (o[0], o[1], o[2]))
    L.append("")
    L.append("topology:")
    L.append("  differential: false")
    L.append("  reject_floating: true")
    L.append("  device_budget: [%d, %d]" % (DEVICE_BUDGET[0], DEVICE_BUDGET[1]))
    if topo.get("allow_inductorless"):
        L.append("  allow_inductorless: true")
        L.append("  max_inductors: %d" % topo["max_ind"])
    else:
        L.append("  allow_inductorless: false")
        L.append("  max_inductors: %d" % topo["max_ind"])
    L.append("  l_min: %s" % _num(L_MIN))
    L.append("  l_max: %s" % _num(topo["l_max"]))
    L.append("")
    L.append("sizing:")
    L.append("  w_um: [1, 200]")
    L.append("  l_fixed: 45e-9")
    L.append("  r_ohm: [50, 20e3]")
    L.append("  c_f: [50e-15, 10e-12]")
    L.append("  vb_v: [0.2, 0.9]")
    return "\n".join(L) + "\n"


def _fmt_constraint(k, v):
    parts = []
    for lim in ("min", "max"):
        if lim in v:
            parts.append("%s: %s" % (lim, v[lim]))
    if "status" in v:
        parts.append("status: %s" % v["status"])
    return "%-12s {%s}" % (k + ":", ", ".join(parts))


