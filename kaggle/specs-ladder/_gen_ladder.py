def build():
    manifest = []
    for spec_id, tier, band_key, nf, s11, s21, idd, iip3, note in LADDER:
        wideband = band_key == "wb"
        if wideband:
            b = dict(type="wideband", **{k: WB[k] for k in ("f0", "f_lo", "f_hi")})
            topo = dict(allow_inductorless=True, l_max=WB["l_max"],
                        max_ind=WB["max_ind"])
            hint = "wideband"
            # wideband uses band-wide S11 (s11_max_db) and adds a ripple cap,
            # matching wideband-sdr's schema.
            ripple = 1.5 if tier == "h" else 2.0
            cons = [
                ("nf_db", {"max": nf}),
                ("s11_max_db", {"max": s11}),
                ("s21_db", {"min": s21}),
                ("s21_ripple_db", {"max": ripple}),
                ("idd_ma", {"max": idd}),
                ("iip3_dbm", {"min": iip3, "status": "unsupported"}),
            ]
            objs = [("nf_db", "min", 1.0), ("s21_db", "max", 0.5),
                    ("idd_ma", "min", 0.5)]
        else:
            nbk = NB[band_key]
            b = dict(type="narrowband", f0=nbk["f0"], f_lo=nbk["f_lo"],
                     f_hi=nbk["f_hi"])
            topo = dict(allow_inductorless=False, l_max=nbk["l_max"],
                        max_ind=nbk["max_ind"])
            hint = nbk["hint"]
            cons = [
                ("nf_db", {"max": nf}),
                ("s11_db", {"max": s11}),
                ("s21_db", {"min": s21}),
                ("idd_ma", {"max": idd}),
                ("iip3_dbm", {"min": iip3, "status": "unsupported"}),
            ]
            # noise-first objective ordering when NF is the binding (tight) axis
            if nf <= 1.8:
                objs = [("nf_db", "min", 1.0), ("s21_db", "max", 0.5),
                        ("idd_ma", "min", 0.5)]
            else:
                objs = [("s21_db", "max", 1.0), ("nf_db", "min", 0.5),
                        ("idd_ma", "min", 0.5)]

        fname = "%s-%s.yaml" % (spec_id, hint)
        name = "%s-%s" % (spec_id, hint)          # spec.name (unique)
        band_lbl = "wideband 0.5-3 GHz" if wideband else (
            "%.3g GHz" % (b["f0"] / 1e9))
        desc = ("capability-v0 %s tier: %s LNA (NF<=%s S11%s%s S21>=%s Idd<=%s)"
                % (tier.upper(), band_lbl, nf,
                   "_max<=" if wideband else "<=", s11, s21, idd))
        text = emit(spec_id, tier, name, desc, b, band_key, cons, objs, topo, note)
        with open(os.path.join(HERE, fname), "w", encoding="utf-8") as fh:
            fh.write(text)
        manifest.append({
            "tier": tier.upper(), "spec_id": spec_id, "name": name,
            "file": fname, "band": band_lbl,
            "band_type": b["type"],
            "nf_max_db": nf, "s11_max_db": s11, "s21_min_db": s21,
            "idd_max_ma": idd, "iip3_min_dbm_advisory": iip3,
            "notes": note,
        })
    with open(os.path.join(HERE, "ladder.json"), "w", encoding="utf-8") as fh:
        json.dump({
            "campaign": "capability-v0",
            "experimental": True,
            "frozen": False,
            "doc": "kaggle/CAMPAIGN-CAPABILITY-V0.md",
            "axes": {
                "band_ghz": [0.9, 1.575, 2.4, 3.5, 5.8, "wideband 0.5-3"],
                "nf_max_db": [3.5, 1.5], "s11_max_db": [-8, -15],
                "s21_min_db": [10, 20], "idd_max_ma": [15, 5],
            },
            "iip3_policy": "declared unsupported; measured post-sizing as an "
                           "ADVISORY column via kaggle/loop/verify.py; NOT gated.",
            "specs": manifest,
        }, fh, indent=2)
        fh.write("\n")
    return manifest


if __name__ == "__main__":
    m = build()
    print("wrote %d spec YAMLs + ladder.json to %s" % (len(m), HERE))
    for r in m:
        print("  %-3s %-22s %-16s NF<=%-4s S11<=%-4s S21>=%-3s Idd<=%-3s"
              % (r["tier"], r["file"], r["band"], r["nf_max_db"],
                 r["s11_max_db"], r["s21_min_db"], r["idd_max_ma"]))
